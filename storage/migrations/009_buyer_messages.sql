CREATE TABLE IF NOT EXISTS `store_buyer_messages` (
  `id` int unsigned NOT NULL AUTO_INCREMENT,
  `tenant_id` int unsigned NOT NULL DEFAULT 1,
  `channel_id` int unsigned DEFAULT NULL,
  `provider` varchar(64) NOT NULL DEFAULT '',
  `external_id` varchar(128) NOT NULL DEFAULT '',
  `thread_id` varchar(128) NOT NULL DEFAULT '',
  `order_external_id` varchar(64) NOT NULL DEFAULT '',
  `buyer_name` varchar(255) NOT NULL DEFAULT '',
  `buyer_email` varchar(255) NOT NULL DEFAULT '',
  `subject` varchar(255) NOT NULL DEFAULT '',
  `body` text NOT NULL,
  `direction` varchar(16) NOT NULL DEFAULT 'inbound',
  `status` varchar(32) NOT NULL DEFAULT 'unread',
  `received_at` datetime DEFAULT NULL,
  `synced_at` datetime DEFAULT NULL,
  `raw_json` json DEFAULT NULL,
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `sbm_ext` (`tenant_id`,`channel_id`,`external_id`),
  KEY `sbm_tenant_status` (`tenant_id`,`status`),
  KEY `sbm_channel` (`channel_id`),
  KEY `sbm_received` (`received_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
