CREATE TABLE IF NOT EXISTS `store_reply_templates` (
  `id` int unsigned NOT NULL AUTO_INCREMENT,
  `tenant_id` int unsigned NOT NULL DEFAULT 1,
  `name` varchar(128) NOT NULL DEFAULT '',
  `body` text NOT NULL,
  `channel_type` varchar(32) DEFAULT NULL,
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_reply_tpl_tenant` (`tenant_id`, `channel_type`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `store_support_cases` (
  `id` int unsigned NOT NULL AUTO_INCREMENT,
  `tenant_id` int unsigned NOT NULL,
  `channel_id` int unsigned NOT NULL,
  `external_id` varchar(64) NOT NULL,
  `kind` varchar(16) NOT NULL DEFAULT 'case',
  `case_type` varchar(64) NOT NULL DEFAULT '',
  `status` varchar(64) NOT NULL DEFAULT '',
  `item_id` varchar(32) NOT NULL DEFAULT '',
  `transaction_id` varchar(32) NOT NULL DEFAULT '',
  `order_id` varchar(64) NOT NULL DEFAULT '',
  `buyer_login` varchar(128) NOT NULL DEFAULT '',
  `claim_amount` decimal(12,2) DEFAULT NULL,
  `claim_currency` varchar(8) NOT NULL DEFAULT '',
  `item_title` varchar(255) NOT NULL DEFAULT '',
  `seller_response_due` datetime DEFAULT NULL,
  `alerted_at` datetime DEFAULT NULL,
  `assigned_user_id` int unsigned DEFAULT NULL,
  `creation_date` datetime DEFAULT NULL,
  `last_modified_date` datetime DEFAULT NULL,
  `summary_json` json DEFAULT NULL,
  `detail_json` json DEFAULT NULL,
  `synced_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_sf_case_channel_ext` (`channel_id`, `kind`, `external_id`),
  KEY `idx_sf_case_tenant` (`tenant_id`),
  KEY `idx_sf_case_channel_status` (`channel_id`, `status`),
  KEY `idx_sf_case_modified` (`last_modified_date`),
  KEY `idx_sf_case_respond_by` (`seller_response_due`),
  KEY `idx_sf_case_assigned` (`assigned_user_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
